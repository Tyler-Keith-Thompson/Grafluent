// Reads Swift sources and writes one Swift file declaring a `Snippet` constant for each region
// between `// snippet: name` and `// snippet end`, its lines dedented. Run by the Snippets
// plugin: `SnippetExtractor <output> <source>...`.
import Foundation

let arguments = CommandLine.arguments.dropFirst()
guard let outputPath = arguments.first else {
    FileHandle.standardError.write(Data("usage: SnippetExtractor <output> <source>...\n".utf8))
    exit(2)
}

/// `name` as a Swift identifier: `dijkstra-walk` becomes `dijkstraWalk`.
func identifier(_ name: String) -> String {
    let parts = name.split(whereSeparator: { !$0.isLetter && !$0.isNumber })
    return parts.enumerated().map { $0.offset == 0 ? String($0.element) : $0.element.prefix(1).uppercased() + $0.element.dropFirst() }.joined()
}

/// `text` as the contents of a Swift string literal.
func escaped(_ text: String) -> String {
    text.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
}

var snippets: [(name: String, lines: [String])] = []
var failures: [String] = []
for path in arguments.dropFirst() {
    guard let text = try? String(contentsOfFile: path, encoding: .utf8) else {
        failures.append("\(path): cannot read")
        continue
    }
    var open: (name: String, lines: [String], line: Int)?
    for (number, line) in text.split(separator: "\n", omittingEmptySubsequences: false).enumerated() {
        let trimmed = line.trimmingCharacters(in: .whitespaces)
        if trimmed.hasPrefix("// snippet: ") {
            if let open { failures.append("\(path):\(number + 1): snippet \(open.name) is still open") }
            open = (String(trimmed.dropFirst("// snippet: ".count)), [], number + 1)
        } else if trimmed == "// snippet end" {
            guard let region = open else {
                failures.append("\(path):\(number + 1): snippet end without a start")
                continue
            }
            let indent = region.lines.filter { !$0.allSatisfy(\.isWhitespace) }.map { $0.prefix(while: { $0 == " " }).count }.min() ?? 0
            snippets.append((region.name, region.lines.map { $0.allSatisfy(\.isWhitespace) ? "" : String($0.dropFirst(indent)) }))
            open = nil
        } else if open != nil {
            open!.lines.append(String(line))
        }
    }
    if let open { failures.append("\(path):\(open.line): snippet \(open.name) has no end") }
}
let names = snippets.map(\.name)
for name in Set(names) where names.filter({ $0 == name }).count > 1 {
    failures.append("snippet \(name) is defined more than once")
}
guard failures.isEmpty else {
    FileHandle.standardError.write(Data((failures.map { "error: \($0)" }.joined(separator: "\n") + "\n").utf8))
    exit(1)
}

var output = "// Generated by SnippetExtractor from the `// snippet:` regions of the Explore sources.\n\nextension Snippet {\n"
for snippet in snippets.sorted(by: { $0.name < $1.name }) {
    output += "    static let \(identifier(snippet.name)) = Snippet(lines: [\n"
    for line in snippet.lines { output += "        \"\(escaped(line))\",\n" }
    output += "    ])\n"
}
output += "}\n"
let url = URL(fileURLWithPath: outputPath)
if (try? String(contentsOf: url, encoding: .utf8)) != output {
    try output.write(to: url, atomically: true, encoding: .utf8)
}
