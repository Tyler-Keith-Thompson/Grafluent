        final class Tally {
            var hashes = 0
        }
        struct Counted: Hashable {
            let name: String
            let tally: Tally
            static func == (lhs: Counted, rhs: Counted) -> Bool { lhs.name == rhs.name }
            func hash(into hasher: inout Hasher) {
                tally.hashes += 1
                hasher.combine(name)
            }
        }
        let tally = Tally()
        let countedG = UndirectedAdjacencyList<Counted>(vertices: ["a", "b", "c"].map { Counted(name: $0, tally: tally) }, edges: [UndirectedEdge(Counted(name: "a", tally: tally), Counted(name: "b", tally: tally)), UndirectedEdge(Counted(name: "b", tally: tally), Counted(name: "c", tally: tally))])
        let countedH = UndirectedAdjacencyList<Counted>(vertices: ["x", "y"].map { Counted(name: $0, tally: tally) }, edges: [UndirectedEdge(Counted(name: "x", tally: tally), Counted(name: "y", tally: tally))])
        let counted = tensorProductView(countedG, countedH)
        tally.hashes = 0
        // Every index-space row, over every vertex.
        for i in 0 ..< 6 {
            _ = Array(counted.neighborIndices(ofIndex: i))
            _ = Array(counted.incidentEdges(ofIndex: i))
            _ = counted.vertex(atIndex: i)
        }
        // The edges by value: each is built from the factors' edges and vertices, with no lookup.
        for position in counted.edges.indices {
            _ = counted.edges[position]
        }
        #expect(counted.vertexIndexBound == 6 && counted.edgeCount == 4)
        #expect(tally.hashes == 0)
        // A pair lookup: one lookup in each factor.
        let index = counted.vertexIndex(of: Pair(Counted(name: "b", tally: tally), Counted(name: "y", tally: tally)))
        #expect(index == 3)
        #expect(tally.hashes == 2)
    }
