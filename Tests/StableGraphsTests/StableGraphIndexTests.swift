    @Test("SG-077 algorithms on a holed graph match the compacted copy", .tags(.conformance))
    func sg077() throws {
        // for each of stronglyConnectedComponents, topologicalSort, shortestPaths (weights by position): on g and on DirectedPseudograph(g) → equal results, edge positions mapped through the conversion's position list
        var graph = StableDirectedGraph<Int>(vertices: [0, 1, 2, 3, 4, 5, 6], edges: [DirectedEdge(from: 0, to: 1), DirectedEdge(from: 1, to: 2), DirectedEdge(from: 2, to: 0), DirectedEdge(from: 2, to: 3), DirectedEdge(from: 3, to: 4), DirectedEdge(from: 4, to: 3), DirectedEdge(from: 4, to: 5), DirectedEdge(from: 5, to: 6), DirectedEdge(from: 6, to: 5), DirectedEdge(from: 0, to: 6), DirectedEdge(from: 3, to: 3), DirectedEdge(from: 1, to: 4)])
        _ = graph.remove(1)
        _ = graph.remove(edgeAt: 5)
        _ = graph.insert(edge: DirectedEdge(from: 6, to: 1))
        _ = graph.insert(edge: DirectedEdge(from: 1, to: 0))
        _ = graph.remove(edgeAt: 8)
        #expect(graph.vertexIndexBound == nil && graph.edgeIndexBound == nil)
        let compacted = DirectedPseudograph<Int>(graph)
        let positions = Array(graph.edges.indices)
        #expect(Array(graph.stronglyConnectedComponents().map { Array($0) }) == Array(compacted.stronglyConnectedComponents().map { Array($0) }))
        // Weights by position, in an array sized edges.endIndex; the copy reads them through `positions`.
        let weight = (0 ..< graph.edges.endIndex).map { ($0 * 7 + 3) % 5 + 1 }
        for source in graph.vertices {
            let tree = graph.dijkstraShortestPaths(from: source) { weight[$0] }
            let copy = compacted.dijkstraShortestPaths(from: source) { weight[positions[$0]] }
            for vertex in graph.vertices {
                #expect(tree.distance(to: vertex) == copy.distance(to: vertex))
                #expect(tree.parentEdge(of: vertex) == copy.parentEdge(of: vertex).map { positions[$0] })
            }
        }
        // An acyclic graph with holes sorts as its compacted copy does.
        var dag = StableDirectedGraph<Int>(vertices: [0, 1, 2, 3, 4, 5], edges: [DirectedEdge(from: 0, to: 1), DirectedEdge(from: 1, to: 2), DirectedEdge(from: 0, to: 2), DirectedEdge(from: 2, to: 3), DirectedEdge(from: 3, to: 4), DirectedEdge(from: 2, to: 4), DirectedEdge(from: 0, to: 5), DirectedEdge(from: 5, to: 4)])
        _ = dag.remove(1)
        _ = dag.remove(edgeAt: 4)
        _ = dag.insert(edge: DirectedEdge(from: 1, to: 3))
        #expect(dag.vertexIndexBound == nil && dag.edgeIndexBound == nil)
        let order = try #require(dag.topologicalSort())
        #expect(order == DirectedPseudograph<Int>(dag).topologicalSort())
        let rank = Dictionary(uniqueKeysWithValues: order.enumerated().map { ($1, $0) })
        #expect(dag.edges.allSatisfy { rank[$0.source]! < rank[$0.target]! })
        #expect(graph.topologicalSort() == nil)
    }
