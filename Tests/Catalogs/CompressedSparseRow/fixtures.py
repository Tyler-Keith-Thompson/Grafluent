def csr(n, E):
    u = sorted(set(E))
    off = [0]*(n+1)
    for a, b in u: off[a+1] += 1
    for i in range(n): off[i+1] += off[i]
    return off, [b for a, b in u]
def show(name, n, E):
    o, t = csr(n, E); io, it = csr(n, [(b, a) for a, b in E])
    print(f"{name}: n={n} m={len(t)}\n  offsets={o}\n  targets={t}\n  T.offsets={io}\n  T.targets={it}")
