# Planted bugs for SpanningTrees; run with `just mutate SpanningTrees`. See scripts/mutate.py.
#
# Known equivalent mutants (they survive by design):
#   (not planted) Dropping Kruskal's stop at n − 1 edges: no later edge can join two components,
#                so only the time would change.
#   density      Picks the other algorithm for the default: both return the canonical forest in
#                the same order, so only the time changes.
#   primrootcheck  Drops `from:`'s own check of the root: looking the absent root up traps anyway
#                (the index lookup or the numbering), only with a less specific message.
#   ed_settlezero  Skips settling when nothing is pending: settling zero changes nothing, so only
#                the time would change (not planted).
#   ed_tie       Breaks equal heap keys by the higher node number: any minimum entering edge is
#                correct, so only which of several optima is returned changes (not planted).
#   ed_bysize    Drops union by size, or the size update on rollback: sizes only keep the finds
#                short; which root a union keeps is never read across a rollback (not planted).
#   ed_internal  Keeps an edge from inside the contracted vertex instead of dropping it: it closes
#                a one-vertex cycle, whose contraction subtracts its reduced cost from the heap
#                and whose expansion restores the edge chosen before (not planted).
#   ed_pairminus Drops the penalty from the penalized costs' subtraction: the only amount with a
#                penalty is a popped added edge's, and that heap then holds added edges alone and
#                belongs to a vertex already settled, so its keys are never read (not planted).
#   st_sameregion  Drops the filter of joins inside one region: the union–find refuses them
#                anyway, so only the sort grows (not planted).
#   st_stop      Drops Mehlhorn's stop at t − 1 joins: no later join can join two sets.
#   st_ontree    Drops marking a path vertex as on the tree: the walk then re-marks edges already
#                taken, so only the time changes (not planted).

