#!/usr/bin/env python3
"""Writes Sources/GraphFormats/SchubfachTable.swift: the table of Giulietti's Schubfach algorithm
(g1 and g0), one entry per decimal exponent k in -324...292.

Entry k is g = floor(10^-k / 2^r) + 1 for the r that puts g in [2^125, 2^126), split as
g1 = g >> 63 and g0 = g mod 2^63: the 126-bit approximation from above that the algorithm's
`rop` multiplies by. Exact rational arithmetic (fractions), so the table is derived from its
definition alone.

    python3 scripts/schubfach_table.py
"""
import os
from fractions import Fraction

K_MIN, K_MAX = -324, 292
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Sources", "GraphFormats", "SchubfachTable.swift")

rows = []
for k in range(K_MIN, K_MAX + 1):
    v = Fraction(10) ** (-k)
    r = v.numerator.bit_length() - v.denominator.bit_length() - 125
    while True:
        b = v / Fraction(2) ** r
        if b < 2 ** 125:
            r -= 1
        elif b >= 2 ** 126:
            r += 1
        else:
            break
    g = (b.numerator // b.denominator) + 1
    rows.append((g >> 63, g & ((1 << 63) - 1)))

with open(OUT, "w") as f:
    f.write("// GENERATED by scripts/schubfach_table.py: do not edit.\n")
    f.write("//\n")
    f.write("// Schubfach's table (Giulietti, \"The Schubfach way to render doubles\"; Java's MathUtils.g1/g0):\n")
    f.write(f"// for each decimal exponent k in {K_MIN}...{K_MAX}, g = floor(10^-k / 2^r) + 1 with r such that\n")
    f.write("// 2^125 <= g < 2^126, as g1 = g >> 63 then g0 = g mod 2^63. Used by DoubleFormatting.swift.\n\n")
    f.write("@usableFromInline internal let _schubfachTable: [UInt64] = [\n")
    for g1, g0 in rows:
        f.write(f"    0x{g1:016X}, 0x{g0:016X},\n")
    f.write("]\n")
print(OUT, len(rows), "entries")
